namespace Ceobe.App.Views;

/// <summary>
/// 页签被切回时重新读一次磁盘/运行态。
///
/// 为什么需要这个：页签是长驻的，而磁盘上的名单、整合包、通道状态会被别处改动
/// （服务端自己写文件、CLI 另开一个进程、地址轮换）。只在 Load 时读一次的话，
/// 用户切回来看到的是陈旧数据——对「白名单」「通道地址」这类信息是危险的，
/// 会让人照着过期地址去分享、或者以为某个玩家还在名单里。
///
/// 只读刷新的页签实现它；带未保存编辑的页（服务器配置/游戏配置）**不要**实现，
/// 否则切回页签会冲掉用户正在改的内容。
/// </summary>
public interface IReloadable
{
    void Reload();
}
